# 3. Favourite Foods 
favourite_foods = ["Pizza", "Chips", "Pasta", "Ice Cream", "Salads"]
print(f"My favourite foods are: {favourite_foods}")

print(f"My first favourite food is {favourite_foods[0]} and last food is {favourite_foods[-1]}")

favourite_foods.append("Chocolate")
print(f"After adding a new food, my favourite foods are: {favourite_foods}")

favourite_foods.remove("Pasta")
print(f"After removing a food, my favourite foods are: {favourite_foods}")

favourite_foods[1] = "Rice"
print(f"The updated list of favourite foods is: {favourite_foods}")

